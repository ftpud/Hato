#!/usr/bin/env python3
"""Embed panel wallpapers from assets/wallpapers/<name>.png into sdk/wallpapers/<name>.ts.

Each module imports only its own theme file, so a panel's bundle carries a single image.
Re-run after replacing artwork, then rebuild and reload the affected modules:
    python3 tools/gen-wallpapers.py && npm run modules:build
"""
import base64, os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "assets", "wallpapers")
OUT = os.path.join(ROOT, "sdk", "wallpapers")
MAX_BYTES = 4 * 1024 * 1024  # stay well under the renderer's 20 MB image cap


def main():
    os.makedirs(OUT, exist_ok=True)
    names = sorted(f[:-4] for f in os.listdir(SRC) if f.endswith(".png"))
    if not names:
        sys.exit(f"no PNGs in {SRC}")
    for name in names:
        with open(os.path.join(SRC, f"{name}.png"), "rb") as f:
            raw = f.read()
        if not raw.startswith(b"\x89PNG\r\n\x1a\n"):
            sys.exit(f"{name}.png is not a PNG")
        if len(raw) > MAX_BYTES:
            sys.exit(f"{name}.png is {len(raw) // 1024} KB; compress it below {MAX_BYTES // 1024} KB")
        data = base64.b64encode(raw).decode()
        with open(os.path.join(OUT, f"{name}.ts"), "w") as f:
            f.write("// Generated by tools/gen-wallpapers.py from assets/wallpapers; do not edit by hand.\n")
            f.write('import type { ImageAttachment } from "../types";\n\n')
            f.write(f'export const wallpaper: ImageAttachment = {{ name: "{name}.png", mimeType: "image/png", data: "{data}" }};\n')
        print(f"{name}: {len(raw) // 1024} KB")


if __name__ == "__main__":
    main()
