// Compiles GPUI's Windows HLSL shaders with the system d3dcompiler_47.dll (what fxc.exe wraps), so
// no Windows SDK is needed. Output replaces vendor/gpui-pre-windows/prebuilt/shaders_bytes.rs.
// Run through tools/windows/compile-shaders.sh.
use std::ffi::c_void;
use std::fmt::Write;
use std::ptr::{null, null_mut};

#[repr(C)]
struct BlobVtbl {
    query_interface: usize,
    add_ref: usize,
    release: unsafe extern "system" fn(*mut Blob) -> u32,
    pointer: unsafe extern "system" fn(*mut Blob) -> *const u8,
    size: unsafe extern "system" fn(*mut Blob) -> usize,
}
#[repr(C)]
struct Blob {
    vtbl: *const BlobVtbl,
}

#[link(name = "d3dcompiler_47")]
extern "system" {
    fn D3DCompileFromFile(file: *const u16, defines: *const c_void, include: *const c_void, entry: *const u8, target: *const u8, flags1: u32, flags2: u32, code: *mut *mut Blob, errors: *mut *mut Blob) -> i32;
}

const D3DCOMPILE_OPTIMIZATION_LEVEL3: u32 = 1 << 15;
const STANDARD_FILE_INCLUDE: *const c_void = 1 as *const c_void;

unsafe fn bytes(b: *mut Blob) -> Vec<u8> {
    let v = &*(*b).vtbl;
    let out = std::slice::from_raw_parts((v.pointer)(b), (v.size)(b)).to_vec();
    (v.release)(b);
    out
}

fn compile(file: &str, entry: &str, target: &str) -> Vec<u8> {
    let wide: Vec<u16> = file.encode_utf16().chain([0]).collect();
    let (e, t) = (format!("{entry}\0"), format!("{target}\0"));
    let (mut code, mut errors) = (null_mut(), null_mut());
    let hr = unsafe { D3DCompileFromFile(wide.as_ptr(), null(), STANDARD_FILE_INCLUDE, e.as_ptr(), t.as_ptr(), D3DCOMPILE_OPTIMIZATION_LEVEL3, 0, &mut code, &mut errors) };
    if hr < 0 {
        let msg = if errors.is_null() { vec![] } else { unsafe { bytes(errors) } };
        panic!("{entry} ({target}) failed {hr:#x}: {}", String::from_utf8_lossy(&msg));
    }
    unsafe { bytes(code) }
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let (src, out) = (&args[1], &args[2]);
    let mut rust = String::from("// @generated by tools/windows/compile-shaders.sh; do not edit.\n");
    let shaders = format!("{src}\\shaders.hlsl");
    let raster = format!("{src}\\color_text_raster.hlsl");
    let modules = [
        ("quad", &shaders), ("shadow", &shaders), ("path_rasterization", &shaders), ("path_sprite", &shaders), ("underline", &shaders),
        ("monochrome_sprite", &shaders), ("subpixel_sprite", &shaders), ("polychrome_sprite", &shaders), ("emoji_rasterization", &raster),
    ];
    for (module, file) in modules {
        for (suffix, name, target) in [("vertex", "VERTEX", "vs_4_1"), ("fragment", "FRAGMENT", "ps_4_1")] {
            let code = compile(file, &format!("{module}_{suffix}"), target);
            write!(rust, "const {}_{name}_BYTES: &[u8] = &[", module.to_uppercase()).unwrap();
            for (i, b) in code.iter().enumerate() {
                if i % 24 == 0 { rust.push_str("\n    "); }
                write!(rust, "{b},").unwrap();
            }
            rust.push_str("\n];\n");
        }
    }
    std::fs::write(out, rust).unwrap();
}
